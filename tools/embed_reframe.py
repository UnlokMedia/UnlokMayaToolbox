"""Embed Reframe (the user's camera-matching tool) into UnlokToolbox.py.

    python tools/embed_reframe.py [path/to/MayaReframeTool] [--check]

Reframe is its own project (MayaReframeTool; by default the folder beside
this repo's parent, Projects/MayaReframeTool). Its package (Build/scripts/reframe) is copied into the
toolbox between the BEGIN / END REFRAME SOURCES markers as plain source text,
the same way its own paste build (Build/tools/build_paste.py) does, so the
toolbox's Reframe tab runs the same code. The text only becomes code when the
Reframe tab is first opened (reframe_package() in the toolbox), so it costs
nothing at paste time.

The toolbox must be pure ASCII: non-ASCII characters (Reframe's em dashes,
arrows, box drawing) are written as \\uXXXX escapes in the string literals,
which decode back to the original text.

--check exits 1 if the embedded copy is out of date (tests use it).
Edit Reframe in its own repo, then run this again.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLBOX = os.path.normpath(os.path.join(HERE, "..", "UnlokToolbox.py"))
DEFAULT_REFRAME = os.path.normpath(os.path.join(HERE, "..", "..", "..", "MayaReframeTool"))
BEGIN = "# --- BEGIN REFRAME SOURCES"
END = "# --- END REFRAME SOURCES ---"
EXCLUDE_DIRS = {"tests", "__pycache__", "data", "vendor"}


def collect_modules(reframe_root):
    """{module name: (is_package, source)} for the reframe package."""
    package_dir = os.path.join(reframe_root, "Build", "scripts", "reframe")
    if not os.path.isdir(package_dir):
        raise SystemExit("No reframe package at %s" % package_dir)
    modules = {}
    for root, dirs, files in os.walk(package_dir):
        dirs[:] = sorted(d for d in dirs if d not in EXCLUDE_DIRS)
        rel = os.path.relpath(root, os.path.dirname(package_dir))
        package = rel.replace(os.sep, ".")
        for name in sorted(files):
            if not name.endswith(".py"):
                continue
            with open(os.path.join(root, name), "r", encoding="utf-8") as f:
                source = f.read().replace("\r\n", "\n")
            if name == "__init__.py":
                modules[package] = (True, source)
            else:
                modules["%s.%s" % (package, name[:-3])] = (False, source)
    return modules


def _literal(source):
    """Source as an ASCII triple-single-quoted literal that evaluates back to it."""
    text = source.replace("\\", "\\\\").replace("'''", "\\'\\'\\'")
    out = []
    for ch in text:
        o = ord(ch)
        if o < 128:
            out.append(ch)
        elif o <= 0xFFFF:
            out.append("\\u%04x" % o)
        else:
            out.append("\\U%08x" % o)
    text = "".join(out)
    if text.endswith("'"):
        text += "\\n"
    return "'''" + text + "'''"


def block(reframe_root):
    modules = collect_modules(reframe_root)
    version = re.search(r'__version__\s*=\s*"([^"]+)"', modules["reframe"][1]).group(1)
    parts = [BEGIN + " (generated by tools/embed_reframe.py from MayaReframeTool; "
             "edit Reframe there, then re-run) ---\n",
             "REFRAME_VERSION = %r\n" % version,
             "_REFRAME_SOURCES = {\n"]
    for name in sorted(modules):
        is_pkg, source = modules[name]
        parts.append("# %s\n# %s\n# %s\n" % ("-" * 60, name, "-" * 60))
        parts.append("%r: (%r, %s),\n" % (name, is_pkg, _literal(source)))
    parts.append("}\n")
    parts.append(END)
    return "".join(parts)


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    reframe_root = os.path.abspath(args[0]) if args else DEFAULT_REFRAME
    new_block = block(reframe_root)
    with open(TOOLBOX, "r", encoding="ascii", newline="") as f:
        text = f.read()
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0:
        raise SystemExit("No %s ... %s markers in %s" % (BEGIN, END, TOOLBOX))
    end += len(END)
    current = text[start:end]
    if check:
        same = current == new_block
        print("embedded Reframe is %s" % ("up to date" if same else "OUT OF DATE: run tools/embed_reframe.py"))
        return 0 if same else 1
    new_block.encode("ascii")
    text = text[:start] + new_block + text[end:]
    if crlf:
        text = text.replace("\n", "\r\n")
    with open(TOOLBOX, "w", encoding="ascii", newline="") as f:
        f.write(text)
    print("embedded Reframe from %s (%d KB)" % (reframe_root, len(new_block) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
